#include <reg52.h>     //包括一个52标准内核的头文件
/****************************IO口定义*****************************/
sbit P10 = P1^0;//要控制的LED灯
sbit P11 = P1^1;//要控制的LED灯
sbit P20 = P2^0;//关闭数码管
sbit P21 = P2^1;//关闭数码管
sbit CS88 = P2^2;//关闭点阵
/******************************主函数*****************************/
void main (void){
   	P1=0x00;  //关闭数码管
	P20=0; //关闭数码管
	P21=0; //关闭数码管
	CS88=0; //关闭点阵
                  //此方法使用1个字节对单个端口赋值
    P1 = 0xFF;    //P1口全部为高电平，对应的LED灯全灭掉，
                  //ff换算成二进制是 1111 1111
   
    P1 = 0xfe;     //P1口的最低位点亮，可以更改数值是其他的灯点亮
                  //0xfe是16进制，0x开头表示16进制数，
                  //fe换算成二进制是 1111 1110 
    while (1)         //主循环
        {
                  //主循环中添加其他需要一直工作的程序
        }
  }

