/*********************************************************************************
*实验名   ：蜂鸣器实验
*实验效果	：程序烧录进后 蜂鸣器发出滴滴的声响
*
*********************************************************************************/
#include<reg52.h>
#define ON 0
#define OFF 1
sbit FM=P2^3;

void delay(unsigned int t)	  //延迟函数
{
    while(--t);	 
}

void main()
{
  while(1)
  {
     FM=ON;	           //蜂鸣器报警
	 delay(50000);     //延迟
	 FM=OFF;		   //蜂鸣器关闭
	 delay(50000); 	   //延迟
  }
}