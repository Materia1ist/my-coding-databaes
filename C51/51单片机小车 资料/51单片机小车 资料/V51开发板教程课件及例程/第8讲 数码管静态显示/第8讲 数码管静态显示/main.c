/*********************************************************************************
*实验名   ：数码管静态显示
*实验效果	：第一个数码管显示字符“b”
*
*********************************************************************************/
#include<reg52.h>
#include "bstv51.h"

sbit DUAN=P2^6;//定义段选
sbit WEI=P2^7;//定义位选

void main()
{
    bstv51_init(); //单片机初始化程序
    
	P0=0x7c;//0111 1100 ————b
	DUAN=1;	//锁存IC使能
	DUAN=0;

	P0=0xfe; // 1111 1110
	WEI=1; //锁存IC使能
	WEI=0;

    while(1);
}